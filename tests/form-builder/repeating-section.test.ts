describe("repeatingSectionEntity — value-shape round-trip (D-04)", () => {
  it("stores and retrieves {instances: [{childA, childB}, {childA}]} unchanged", async () => {
    const { formBuilder } = await import("@/lib/form-builder/index");
    const builderStore = createBuilderStore(formBuilder);

    // Build a schema with one repeatingSection containing two child text fields
    const { id: repId } = builderStore.addEntity({
      type: "repeatingSection",
      attributes: { title: "Entries", description: "", minInstances: 0 },
    });
    const { id: childAId } = builderStore.addEntity({
      type: "textField",
      attributes: { label: "Field A", required: false, placeholder: "", helpText: "", prefillSource: "" },
    });
    const { id: childBId } = builderStore.addEntity({
      type: "textField",
      attributes: { label: "Field B", required: false, placeholder: "", helpText: "", prefillSource: "" },
    });
    builderStore.setEntityParent(childAId, repId);
    builderStore.setEntityParent(childBId, repId);

    const schema = builderStore.getSchema();
    const interpreterStore = createInterpreterStore(formBuilder, schema);

    // Set a multi-instance value matching the D-04 shape
    const instancesValue = {
      instances: [
        { [childAId]: "aaa", [childBId]: "bbb" },
        { [childAId]: "ccc" },
      ],
    };

    interpreterStore.setEntityValue(repId, instancesValue);

    const values = interpreterStore.getEntitiesValues();
    expect(values[repId]).toEqual(instancesValue);
  });
});

