import { describe, it, expect } from "vitest";
import { createBuilderStore, createInterpreterStore } from "@coltorapps/builder";

// ============================================================
// Nesting tests (setEntityParent / unsetEntityParent API)
// ============================================================

describe("repeatingSectionEntity — nesting API", () => {
  it("setEntityParent moves child textField out of root and into repeatingSection.children", async () => {
    const { formBuilder } = await import("@/lib/form-builder/index");
    const builderStore = createBuilderStore(formBuilder);

    const { id: repId } = builderStore.addEntity({
      type: "repeatingSection",
      attributes: { title: "Fire Doors", description: "", minInstances: 0 },
    });

    const { id: textId } = builderStore.addEntity({
      type: "textField",
      attributes: {
        label: "Door Location",
        required: false,
        placeholder: "",
        helpText: "",
        prefillSource: "",
      },
    });

    // Initially both are in root
    expect(builderStore.getSchema().root).toContain(repId);
    expect(builderStore.getSchema().root).toContain(textId);

    // Nest the textField inside the repeatingSection
    builderStore.setEntityParent(textId, repId);

    const schema = builderStore.getSchema();

    // repeatingSection remains in root
    expect(schema.root).toContain(repId);

    // textField is NO LONGER in root
    expect(schema.root).not.toContain(textId);

    // repeatingSection.children contains the textField
    expect(schema.entities[repId]?.children).toContain(textId);

    // textField.parentId points to the repeatingSection
    expect(schema.entities[textId]?.parentId).toBe(repId);
  });

  it("unsetEntityParent returns child textField to root", async () => {
    const { formBuilder } = await import("@/lib/form-builder/index");
    const builderStore = createBuilderStore(formBuilder);

    const { id: repId } = builderStore.addEntity({
      type: "repeatingSection",
      attributes: { title: "Rooms", description: "" },
    });
    const { id: textId } = builderStore.addEntity({
      type: "textField",
      attributes: { label: "Room Name", required: false, placeholder: "", helpText: "", prefillSource: "" },
    });

    builderStore.setEntityParent(textId, repId);
    expect(builderStore.getSchema().root).not.toContain(textId);

    builderStore.unsetEntityParent(textId);
    const schema = builderStore.getSchema();

    // Child is back in root
    expect(schema.root).toContain(textId);
    // No longer in parent's children
    expect(schema.entities[repId]?.children).not.toContain(textId);
    // parentId is cleared
    expect(schema.entities[textId]?.parentId).toBeUndefined();
  });

  it("childrenAllowed: true — can nest multiple children in repeatingSection", async () => {
    const { formBuilder } = await import("@/lib/form-builder/index");
    const builderStore = createBuilderStore(formBuilder);

    const { id: repId } = builderStore.addEntity({
      type: "repeatingSection",
      attributes: { title: "Items", description: "" },
    });
    const { id: child1Id } = builderStore.addEntity({
      type: "textField",
      attributes: { label: "Field A", required: false, placeholder: "", helpText: "", prefillSource: "" },
    });
    const { id: child2Id } = builderStore.addEntity({
      type: "numberField",
      attributes: { label: "Field B", required: false },
    });

    // Nesting both should succeed (childrenAllowed: true)
    expect(() => {
      builderStore.setEntityParent(child1Id, repId);
      builderStore.setEntityParent(child2Id, repId);
    }).not.toThrow();

    const schema = builderStore.getSchema();
    expect(schema.entities[repId]?.children).toContain(child1Id);
    expect(schema.entities[repId]?.children).toContain(child2Id);
  });

  it("setEntityParent into a textField (childrenAllowed: false) throws", async () => {
    const { formBuilder } = await import("@/lib/form-builder/index");
    const builderStore = createBuilderStore(formBuilder);

    const { id: textParentId } = builderStore.addEntity({
      type: "textField",
      attributes: { label: "Parent", required: false, placeholder: "", helpText: "", prefillSource: "" },
    });
    const { id: childId } = builderStore.addEntity({
      type: "textField",
      attributes: { label: "Child", required: false, placeholder: "", helpText: "", prefillSource: "" },
    });

    // textField has childrenAllowed: false (default), so nesting should throw
    expect(() => {
      builderStore.setEntityParent(childId, textParentId);
    }).toThrow();
  });
});

