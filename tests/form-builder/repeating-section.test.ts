describe("repeatingSectionEntity.validate() — container shape", () => {
  it("returns the value unchanged when instances is a valid non-empty array", async () => {
    const { repeatingSectionEntity } = await import(
      "@/lib/form-builder/entities/repeating-section"
    );
    const input = { instances: [{}, {}, {}] };
    const result = repeatingSectionEntity.validate(input, {} as never);
    expect(result).toEqual(input);
  });

  it("throws with 'instances' in the error message when instances is not an array", async () => {
    const { repeatingSectionEntity } = await import(
      "@/lib/form-builder/entities/repeating-section"
    );
    expect(() =>
      repeatingSectionEntity.validate({ instances: 42 } as never, {} as never)
    ).toThrow(/instances/);
  });
});

